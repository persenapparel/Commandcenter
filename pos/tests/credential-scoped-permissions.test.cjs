'use strict';
/* Credential-scoped owner permissions: staging source-contract checks only.
   This suite never connects to Supabase or modifies sales/employee records. */
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const base=path.resolve(__dirname,'..');
const load=p=>fs.readFileSync(path.join(base,p),'utf8');
const html=load('register.html'),js=load('register.js'),css=load('christmas-cashier.css');
const status=load('sql/staging_owner_badge_scoped_status_20261119.sql');
const grants=load('sql/staging_revoke_badge_shifts_on_register_denial_20261119.sql');
assert.doesNotThrow(()=>new vm.Script(js), 'register JS syntax must remain valid');
assert.match(html, /id="staff-register-access"[^>]*hidden/, 'staff grant controls hidden until status confirms existing badge');
assert.match(html,/id="staff-grant-register"[^>]*disabled/);
assert.match(html,/id="staff-revoke-register"[^>]*disabled/);
assert.match(html,/id="staff-register-access-status" role="status" aria-live="polite"/);
assert.match(js,/db\.rpc\('pos_owner_badge_slot_status',\{p_slot:slot,p_register:register\.id\}\)/);
assert.match(js,/db\.rpc\('pos_owner_set_badge_register_access',\{\s*p_register:register\.id,p_staff_id:snapshot\.staffId,p_allowed:allowed/);
assert.doesNotMatch(js,/db\.rpc\('pos_staff_set_register_access'/, 'legacy user-ID grant caller forbidden');
assert.match(js,/permissionUpdatePending/, 'duplicate owner grant mutation must be gated');
assert.match(js,/if\(!allowed&&!window\.confirm\(/, 'revocation requires explicit confirmation');
assert.match(js,/employeeSlotStatus=null;\s*allow\.disabled=true;revoke\.disabled=true;/, 'ambiguous permission writes must disable controls');
assert.match(js,/error\?\.code!=='PGRST202'/, 'read-only status fallback allowed solely when new RPC unavailable');
assert.match(css, /\.staff-register-access\[hidden\]\{display:none!important\}/);
assert.match(status,/public\.is_persen_admin\(\)/, 'owner-only status');
assert.match(status,/r\.id=p_register and r\.owner_id=v_owner and r\.active=true/, 'current register scope');
assert.match(status,/c\.auth_user_id=v_owner and c\.staff_role='cashier'/, 'owner-paired credential');
assert.match(status,/'staffId',v_staff\.id/, 'do not substitute shared auth user ID');
assert.match(status,/'registerAllowed',v_allowed/, 'permission response reflects only selected register');
assert.doesNotMatch(status,/pin_hash|badge_digest|shift_secret|access_token/, 'status must not return credential secrets');
assert.match(status,/revoke all on function public\.pos_owner_badge_slot_status\(integer,uuid\)/);
assert.match(status,/revoke all on function public\.pos_staff_set_register_access\(uuid,uuid,boolean\)/,'broad user-ID legacy access revoked');
assert.match(grants,/where id=p_staff_id and auth_user_id=v_owner/);
assert.match(grants,/and staff_role='cashier' and enabled=true/, 'grant cannot target owner credential');
assert.match(grants,/where id=p_register and owner_id=v_owner and active=true/);
assert.match(grants,/if not p_allowed then/, 'revocations invalidate credential shifts');
assert.match(grants,/set revoked_at=now\(\)/, 'revoke active employee shift secrets');
assert.match(grants,/capability_digest=null/, 'revoke guest capabilities');
assert.match(grants,/revoke all on function public\.pos_owner_set_badge_register_access\(uuid,uuid,boolean\)/);
console.log('PASS credential scoped employee grant UI and reviewed staging SQL contracts.');
