/* Static customer-iPad wizard checks. Never connects to a live database. */
'use strict';
const fs=require('node:fs');
const assert=require('node:assert/strict');
const html=fs.readFileSync('pos/display.html','utf8');
const js=fs.readFileSync('pos/display.js','utf8');
const sql=fs.readFileSync('pos/pos-schema-review.sql','utf8');
const build=fs.readFileSync('pos/build-pages.mjs','utf8');
const wizard=require('./checkout-flow.js');
const sections=[...html.matchAll(/<section class="wizard-step" data-step="([^"]+)"/g)].map(m=>m[1]);
assert.deepEqual(sections,wizard.steps.map(s=>s.id),'Eight pages must match wizard order');
assert.match(html,/id="phone-display"[^>]*name="phone"[^>]*readonly/,'Phone must use read-only display and on-screen keypad');
assert.match(html,/id="phone-keypad"/);
for(const key of '1234567890')assert.ok(html.includes('data-digit="'+key+'"'),'Missing number key '+key);
assert.ok(html.includes('data-digit="back"')&&html.includes('data-digit="clear"'));
for(const mode of ['print','email','both','none'])assert.ok(html.includes('name="receipt_mode" value="'+mode+'"'));
assert.ok(!html.includes('receipt_sms')&&!js.includes('receipt_sms')&&!sql.includes('receipt_sms'));assert.doesNotMatch(html,/Apple Cash information|value="apple_cash_info"/i);
assert.match(html,/id="email-address"[^>]+name="email"/);
for(const step of ['promos','rating','custom'])assert.ok(sections.includes(step),'Missing one-question page '+step);
assert.ok(html.includes('id="wizard-back"')&&html.includes('id="wizard-next"'));
assert.ok(js.includes('resetWizard()'));
assert.ok(build.includes("'checkout-flow.js'"),'Cloudflare POS build must copy wizard helper');
assert.ok(sql.includes('p_email_receipt boolean default false'),'Backend must support email preference');
const cashier=fs.readFileSync('pos/register.html','utf8');
const cashierJs=fs.readFileSync('pos/register.js','utf8');
assert.ok(html.includes('id="wizard-help"')&&js.includes("pos_set_customer_progress"),'Customer help button must report progress');
assert.ok(cashier.includes('id="customer-help-alert"')&&cashierJs.includes("customer_step"),'Cashier must show step and help');
assert.ok(cashier.includes('id="cashier-progress-bar"'),'Cashier progress indicator missing');
assert.ok(cashier.includes('@persenapparel')&&!cashier.includes('copy-apple-cash'),'Cashier payment references missing');
assert.ok(js.includes('identifier:')&&js.includes('@persenapparel')&&!js.includes('apple_cash_info'),'Customer payment references missing');
assert.ok(sql.includes('public.pos_set_customer_progress(')&&sql.includes('help_requested boolean not null default false'),'SQL draft must support assistance');
assert.ok(!/jsonb_build_object\([^)]*phone/i.test(sql.slice(sql.indexOf('public.pos_set_customer_progress'),sql.indexOf('public.pos_submit_customer'))),'Step updates should not include customer contact details');
const cashierStatusSource=cashierJs.slice(cashierJs.indexOf('async function status()'),cashierJs.indexOf('async function begin()'));
assert.ok(!/\bdraw\(\)/.test(cashierStatusSource),'Customer polling must not rebuild cart inputs');
assert.ok(cashierJs.includes('syncCheckoutUI();renderCash();'),'Polling should only update lightweight checkout controls');
assert.ok(cashierJs.includes('button.disabled=remaining<=0||!priced')&&cashierJs.includes('tile.disabled=!ready.length')&&cashierJs.includes('price>0'),'Unpriced inventory must never be offered as a selectable product');
assert.ok(cashierJs.includes("upsert(metadata,{onConflict:'stock_id'})"),'Existing variants need a price editor');
assert.ok(cashier.includes('id="variant-dialog"')&&cashier.includes('id="open-register"'),'Cashier should expose quick product picker and launch action');
const admin=fs.readFileSync('pos/admin.html','utf8');
const adminJs=fs.readFileSync('pos/admin.js','utf8');
assert.ok(admin.includes('id="create-products"')&&admin.includes('id="inventory-list"'),'Laptop back office must have product setup and inventory editor');
const hub=fs.readFileSync('inventory-hub.js','utf8');
assert.ok(adminJs.includes("link.href='inventory.html'")&&hub.includes('inventory_save_size_grid')&&hub.includes('inventory_save_event_tiles'),'Laptop routes to the shared atomic inventory actions');
assert.ok(build.includes("'inventory.html'")&&build.includes("'inventory-hub.js'"),'Deploy shared inventory editor');
assert.ok(build.includes("'admin.html'")&&build.includes("'admin.css'")&&build.includes("'admin.js'"),'POS deployment must include laptop back office assets');
console.log('Persen POS kiosk + quick cashier + separate laptop admin checks passed.');
